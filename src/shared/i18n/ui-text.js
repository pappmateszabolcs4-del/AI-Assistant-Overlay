function normalizeLang(lang) {
  return String(lang || '').toLowerCase();
}

function getUiText(lang, overrides = {}) {
  const normalized = normalizeLang(lang);
  const base = UI_TEXT[DEFAULT_LANG] || {};
  const target = UI_TEXT[normalized] || {};
  const extra = overrides && typeof overrides === 'object' ? overrides : {};
  return { ...base, ...target, ...extra };
}

function getMissingKeys(lang, overrides = {}) {
  const normalized = normalizeLang(lang);
  const base = UI_TEXT[DEFAULT_LANG] || {};
  const target = UI_TEXT[normalized] || {};
  const extra = overrides && typeof overrides === 'object' ? overrides : {};
  return Object.keys(base).filter((key) => typeof (target[key] ?? extra[key]) !== 'string');
}

